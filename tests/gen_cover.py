#!/usr/bin/env python3
"""gen_cover.py — generate tests/cover.fam, a program that exercises every
public stdlib word so tools/verify_fsm.py can prove the EMITTED code (word
bodies + fam's call/control/literal emitters) is a bounded FSM.

It is also a runtime self-check: compiled and run, it prints known results,
so a hex typo that stays legal-RV32I-but-wrong is still caught.

Coverage notes:
  - verify_fsm uses STATIC reachability (walks both branch edges), so words
    placed behind an always-false `if` (getc) are still proven, just not run.
  - the >2KB padding blocks force fam's forward (if/then) and backward
    (begin/until) backpatched `jal`s past the old B-type danger zone.

Regenerate: python3 tests/gen_cover.py   (writes tests/cover.fam)
"""
import os

PAD_UNITS = 160          # each "0 lit drop" ~= 20 B emitted; 160 -> ~3.2 KB > 2 KB
PAD = " ".join(["0 lit drop"] * PAD_UNITS)

L = []
def w(s=""): L.append(s)

w("\\ tests/cover.fam — GENERATED by tests/gen_cover.py.  Do not edit.")
w("\\ Exercises every public stdlib word (static proof corpus + runtime self-check).")
w("")
w("\\ ---- user-defined words: covers user :M / : and the runtime return-BST ----")
w(":M SP 20 lit putc ;            \\ 0x20 space")
w(":M NL 0A lit putc ;            \\ 0x0A newline")
w(": sq dup * ;                   \\ a user `:` word (call + gen_bst)")
w("")
w("( block-comment coverage for `(` `)` — nested ( like this ) too )")
w('"== cover ==" puts NL')
w("")
w("\\ ---- literals: char, escape, space, decimal, negative, hex, string ----")
w("'A' lit putc 'B' lit putc '\\n' lit putc      \\ -> AB")
w("' ' lit putc                                  \\ space char literal")
w("2A lit u. SP                                  \\ hex 0x2A -> 42")
w("42u lit u. SP                                 \\ decimal -> 42")
w("-7 lit . NL                                   \\ signed -> -7")
w('"str\\n" puts                                 \\ string + escape -> str')
w("")
w("\\ ---- arithmetic: 7 op 3 ----")
w("7u lit 3u lit + u. SP                          \\ 10")
w("7u lit 3u lit - u. SP                          \\ 4")
w("7u lit 3u lit * u. SP                          \\ 21")
w("7u lit 3u lit / u. SP                          \\ 2")
w("7u lit 3u lit % u. NL                          \\ 1")
w("5u lit sq u. NL                                \\ user word: 25")
w("")
w("\\ ---- comparisons (Forth flag -1/0, printed signed) ----")
w("3u lit 3u lit = . SP                           \\ -1")
w("3u lit 4u lit <> . SP                          \\ -1")
w("3u lit 4u lit < . SP                           \\ -1")
w("4u lit 3u lit > . SP                           \\ -1")
w("3u lit 4u lit u< . SP                          \\ -1")
w("4u lit 3u lit u> . SP                          \\ -1")
w("-1 lit 0< . SP                                 \\ -1")
w("0 lit 0= . NL                                  \\ -1")
w("")
w("\\ ---- bitwise / shifts ----")
w("C lit 3u lit and u.x SP                        \\ 00000000")
w("C lit 3u lit or  u.x SP                        \\ 0000000F")
w("C lit 6u lit xor u.x SP                        \\ 0000000A")
w("0 lit invert u.x SP                            \\ FFFFFFFF")
w("1u lit 4u lit lshift u. SP                     \\ 16")
w("40u lit 2u lit rshift u. NL                    \\ 16")
w("")
w("\\ ---- stack ops ----")
w("5u lit dup + u. SP                             \\ dup -> 10")
w("1u lit 2u lit drop u. SP                       \\ drop -> 1")
w("1u lit 2u lit swap - u. SP                     \\ swap -> 1")
w("1u lit 2u lit over + + u. SP                   \\ over -> 4")
w("1u lit 2u lit 3u lit rot drop drop u. SP       \\ rot (1 2 3->2 3 1) top=1 -> 1")
w("1u lit 2u lit nip u. SP                        \\ nip -> 2")
w("1u lit 2u lit tuck + + u. SP                   \\ tuck (1 2->2 1 2) -> 5")
w("1u lit 2u lit 2dup + + + u. SP                 \\ 2dup (1 2 1 2) -> 6")
w("9u lit ?dup + u. SP                            \\ ?dup nonzero -> 18")
w("1u lit 2u lit 3u lit -rot drop drop u. SP      \\ -rot (1 2 3->3 1 2) top=2 -> 2")
w("8u lit 9u lit 2drop 1u lit 1- u. NL            \\ 2drop then 1- -> 0")
w("")
w("\\ ---- memory: variable @ ! c@ c! h@ h! ----")
w("variable                                       \\ ( -- a )")
w("dup 7B lit swap !   dup @   u.x SP             \\ 0000007B")
w("dup FF lit swap c!  dup c@  u.x SP             \\ 000000FF")
w("dup BEEF lit swap h! dup h@ u.x NL             \\ 0000BEEF")
w("drop")
w("")
w("\\ ---- control flow: if/else/then ----")
w("1 lit if 'Y' lit putc else 'N' lit putc then   \\ Y")
w("0 lit if 'Y' lit putc else 'N' lit putc then NL \\ N")
w("")
w("\\ ---- begin/until : 3 2 1 ----")
w("3u lit begin dup u. SP 1- dup 0= until drop NL")
w("\\ ---- begin/while/repeat : 3 2 1 ----")
w("3u lit begin dup 0= 0= while dup u. SP 1- repeat drop NL")
w("\\ ---- do/loop + i : 0 1 2 ----")
w("3u lit 0 lit do i u. SP loop NL")
w("\\ ---- nested do/loop + i/j : 00 01 10 11 ----")
w("2u lit 0 lit do 2u lit 0 lit do j u. i u. SP loop loop NL")
w("")
w("\\ ---- getc: statically proven, never run (always-false guard) ----")
w("0 lit if getc drop then")
w("\\ ---- alloc: bump 16 bytes ----")
w("10u lit alloc drop")
w("")
w("\\ ---- adversarial: forward backpatched jal across >2KB body ----")
w("1 lit if " + PAD + " then")
w("\\ ---- adversarial: backward backpatched jal across >2KB body ----")
w("2u lit begin " + PAD + " 1- dup 0= until drop")
w("")
w("\\ ---- big / edge literals ----")
w("FFFFFFFF lit u.x NL                            \\ FFFFFFFF (U32_MAX)")
w("7FFFFFFF lit u.x NL                            \\ 7FFFFFFF (I32_MAX)")
w("-2147483648 lit u.x NL                         \\ 80000000 (I32_MIN)")
w("2147483647u lit u. NL                          \\ 2147483647")
w("")
w('"== done ==" puts NL')
w("bye")
w("")

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "cover.fam")
open(out, "w").write("\n".join(L))
print(f"wrote {out}  ({len(L)} lines, PAD_UNITS={PAD_UNITS})")
